export const getAdminStatusTone = (value) => {
  const normalized = String(value || "").toLowerCase();
  if (normalized.includes("healthy") || normalized.includes("active") || normalized.includes("enabled")) {
    return "bg-emerald-100 text-emerald-700";
  }
  if (normalized.includes("degraded") || normalized.includes("risk") || normalized.includes("medium") || normalized.includes("high")) {
    return "bg-amber-100 text-amber-700";
  }
  if (normalized.includes("down") || normalized.includes("blocked") || normalized.includes("suspended") || normalized.includes("critical") || normalized.includes("disabled")) {
    return "bg-rose-100 text-rose-700";
  }
  return "bg-slate-100 text-slate-700";
};

